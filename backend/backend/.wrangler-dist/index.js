async function handle(request, env) {
  const url = new URL(request.url);
  const segments = url.pathname.replace(/^\/api\/?/u, "").split("/").filter(Boolean);
  if (request.method === "POST" && segments.join("/") === "auth/login") {
    return withDb(env, async (db) => login(request, env, db));
  }
  const session = await readSession(request, env);
  if (!session) return { error: "Sess\xE3o inv\xE1lida ou expirada.", status: 401 };
  return withDb(env, async (db) => {
    if (request.method === "GET" && segments[0] === "dashboard") return { data: await dashboard(db, session.sub) };
    const [resource, id] = segments;
    if (request.method === "GET" && !id) return { data: await listResource(db, resource, session.sub) };
    if (request.method === "POST" && !id) return { data: await createResource(db, resource, session.sub, await readJson(request)), status: 201 };
    if (request.method === "PUT" && id) return { data: await updateResource(db, resource, session.sub, id, await readJson(request)) };
    if (request.method === "DELETE" && id) {
      await deleteResource(db, resource, session.sub, id);
      return { data: null, status: 204 };
    }
    return { error: "Rota n\xE3o encontrada.", status: 404 };
  });
}
